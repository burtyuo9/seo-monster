// Все переводы
export const translations: Record<Language, Translations> = {
  en,
  ru,
};

// Функция получения перевода
export function t(key: string, lang: Language = DEFAULT_LANGUAGE, params?: Record<string, string | number>): string {
  let text = translations[lang]?.[key] || translations[DEFAULT_LANGUAGE]?.[key] || key;
  
  // Подстановка параметров
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  
  return text;
}

// Хук для использования в React компонентах
export function useTranslation(lang: Language = DEFAULT_LANGUAGE) {
  return {
    t: (key: string, params?: Record<string, string | number>) => t(key, lang, params),
    lang,
  };
}
